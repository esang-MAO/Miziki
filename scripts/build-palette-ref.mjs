#!/usr/bin/env node
// Rebuilds the generated WADA block of src/ui/palette-ref.js from
// docs/design/colour/colors.json (the sanzo-wada.dmbk.io dump — see
// colors.json.SOURCE.md for its source and licence).
//
// Only names and hex values leave this script. Combination membership
// (which colours form which numbered combination) never ships — see
// docs/37_COLOUR.md's rights note (recommendation 10). This used to also
// derive per-colour partner counts from that membership (CO1's
// `PARTNERS_INDEX`), for CO4's planned gatefold anchor lookup; CO4 asked
// Ken whether that lookup could use Wada-derived data at all, and he
// chose a hand-picked table instead (src/ui/art-color.js), so the
// derivation and its output are both removed — nothing here reads
// `combinations` any more.
//
// Run: node scripts/build-palette-ref.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const SPELLING_FIXES = {
  'Sulpher Yellow': 'Sulphur Yellow', // Ridgway spells it "Sulphur"
  'Calamine BLue': 'Calamine Blue', // data-entry capitalization typo
};

function buildWada() {
  const raw = JSON.parse(
    readFileSync(join(root, 'docs/design/colour/colors.json'), 'utf8')
  );
  raw.sort((a, b) => a.index - b.index);

  return raw.map(({ name, hex }) => ({
    name: SPELLING_FIXES[name] || name,
    hex: hex.toLowerCase(),
  }));
}

function render(WADA) {
  // [name, hex] pairs, not {name, hex} objects — cuts the repeated "name:"/
  // "hex:" keys, which add up over 159 rows.
  const wadaLines = WADA.map((c) => `  [${JSON.stringify(c.name)},${JSON.stringify(c.hex)}],`).join('\n');

  return `// GENERATED by scripts/build-palette-ref.mjs — do not hand-edit this block.
// Source: docs/design/colour/colors.json (see colors.json.SOURCE.md).
// Each WADA row is [name, hex], not {name, hex} — see palette-ref.js.
export const WADA_PAIRS = [
${wadaLines}
];
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const WADA = buildWada();
  const generated = render(WADA);
  const outPath = join(root, 'src/ui/palette-ref.generated.js');
  writeFileSync(outPath, generated);
  console.log(`Wrote ${WADA.length} colours to ${outPath}`);
}

export { buildWada };
