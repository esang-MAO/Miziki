#!/usr/bin/env node
// Rebuilds the generated WADA/PARTNERS block of src/ui/palette-ref.js from
// docs/design/colour/colors.json (the sanzo-wada.dmbk.io dump — see
// colors.json.SOURCE.md for its source and licence).
//
// Only names, hex values and DERIVED partner counts leave this script.
// Combination membership (which colours form which numbered combination)
// never ships — see docs/37_COLOUR.md's rights note (recommendation 10).
//
// Run: node scripts/build-palette-ref.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const SPELLING_FIXES = {
  'Sulpher Yellow': 'Sulphur Yellow', // Ridgway spells it "Sulphur"
  'Calamine BLue': 'Calamine Blue', // data-entry capitalization typo
};

function buildWadaAndPartners() {
  const raw = JSON.parse(
    readFileSync(join(root, 'docs/design/colour/colors.json'), 'utf8')
  );
  raw.sort((a, b) => a.index - b.index);

  const WADA = raw.map(({ name, hex }) => ({
    name: SPELLING_FIXES[name] || name,
    hex: hex.toLowerCase(),
  }));

  // Invert combination membership: colours sharing a combination id become
  // partners of each other. combo -> [colour names]
  const comboMembers = new Map();
  for (const c of raw) {
    const name = SPELLING_FIXES[c.name] || c.name;
    for (const combo of c.combinations) {
      if (!comboMembers.has(combo)) comboMembers.set(combo, []);
      comboMembers.get(combo).push(name);
    }
  }

  const counts = {};
  for (const members of comboMembers.values()) {
    for (let i = 0; i < members.length; i++) {
      for (let j = 0; j < members.length; j++) {
        if (i === j) continue;
        const a = members[i];
        const b = members[j];
        counts[a] = counts[a] || {};
        counts[a][b] = (counts[a][b] || 0) + 1;
      }
    }
  }

  // Keep only each colour's strongest partners — enough for CO4's anchor
  // lookup (which only needs a handful of near-neutral-dark candidates per
  // colour) without shipping the full 159x159 co-occurrence table. Encoded
  // by WADA array index, not name, to keep the generated file's string
  // content to one copy of each name (the 12 KB budget in CO1).
  const TOP_N_PARTNERS = 4;
  const nameToIndex = new Map(WADA.map((c, i) => [c.name, i]));
  const PARTNERS_INDEX = WADA.map((c) => {
    const ranked = Object.entries(counts[c.name] || {}).sort((a, b) => b[1] - a[1]);
    return ranked.slice(0, TOP_N_PARTNERS).map(([name, count]) => [nameToIndex.get(name), count]);
  });

  return { WADA, PARTNERS_INDEX };
}

function render({ WADA, PARTNERS_INDEX }) {
  // [name, hex] pairs, not {name, hex} objects — cuts the repeated "name:"/
  // "hex:" keys, which add up over 159 rows.
  const wadaLines = WADA.map((c) => `  [${JSON.stringify(c.name)},${JSON.stringify(c.hex)}],`).join('\n');

  const indexLines = PARTNERS_INDEX.map((pairs) => `  [${pairs.map(([i, n]) => `[${i},${n}]`).join(',')}],`).join(
    '\n'
  );

  return `// GENERATED by scripts/build-palette-ref.mjs — do not hand-edit this block.
// Source: docs/design/colour/colors.json (see colors.json.SOURCE.md).
// Each WADA row is [name, hex], not {name, hex} — see palette-ref.js.
export const WADA_PAIRS = [
${wadaLines}
];

// Derived partner counts per colour (how often two colours co-occur in a
// Wada combination), by WADA array index — not name — to keep this file's
// string content to one copy of each name. PARTNERS_INDEX[i] is WADA[i]'s
// top partners as [partnerIndex, count] pairs, count descending. The
// combination table itself never ships.
export const PARTNERS_INDEX = [
${indexLines}
];
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { WADA, PARTNERS_INDEX } = buildWadaAndPartners();
  const generated = render({ WADA, PARTNERS_INDEX });
  const outPath = join(root, 'src/ui/palette-ref.generated.js');
  writeFileSync(outPath, generated);
  const total = PARTNERS_INDEX.reduce((n, p) => n + p.length, 0);
  console.log(`Wrote ${WADA.length} colours and ${total} partner pairs to ${outPath}`);
}

export { buildWadaAndPartners };
